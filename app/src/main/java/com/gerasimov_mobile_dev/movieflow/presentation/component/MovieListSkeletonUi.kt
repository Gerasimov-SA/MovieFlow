@Composable
fun MoviesListSkeletonUi(
    itemCount: Int = 6,
    modifier: Modifier = Modifier
) {
    LazyColumn(
        modifier = modifier.fillMaxSize(),
        contentPadding = PaddingValues(8.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        items(itemCount) { _ ->
            MovieItemSkeletonUi()
        }
    }
}
@Composable
fun MovieItemSkeletonUi(
    modifier: Modifier = Modifier
) {
    AnimatedSkeletonBox(
        modifier = Modifier
            .fillMaxWidth()
            .height(130.dp)
            .padding(8.dp),
        cornerRadius = 12.dp
    )
}


